# Простой граф: из "A" можно уйти в "B" и "C"
graph = {
    "A": ["B", "C"],
    "B": ["D"],
    "C": [],
    "D": []
}



# Взвешенный граф: из "A" в "B" путь стоит 5, а в "C" — 2
graph = {
    "A": {"B": 5, "C": 2},
    "B": {"D": 1},
    "C": {"D": 8},
    "D": {}
}




# Ориентированный (одностороннее движение): связь прописывается только в одну сторону ("A": ["B"]).

# Неориентированный (двусторонняя дорога): связь обязательно прописывается в обе стороны.




# Двусторонняя связь между A и B
graph = {
    "A": ["B"],
    "B": ["A"]
}


